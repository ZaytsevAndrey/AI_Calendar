/**
 * One-off generator for the Postgres baseline migration: the exact DDL that
 * `synchronize` would run on an EMPTY database for the current entities.
 * Usage (empty database only):
 *   DATABASE_URL=postgres://…/empty npx ts-node src/scripts/generate-baseline-migration.ts <Name> <timestamp>
 * Prints a migration class to stdout.
 */
import 'reflect-metadata';
import { join } from 'path';
import { DataSource } from 'typeorm';

async function main(): Promise<void> {
  const [name = 'Baseline', timestamp = String(Date.now())] = process.argv.slice(2);
  const ds = await new DataSource({
    type: 'postgres',
    url: process.env.DATABASE_URL,
    entities: [join(__dirname, '..', 'modules', '**', '*.entity.{ts,js}').replace(/\\/g, '/')],
    synchronize: false,
  }).initialize();
  const sql = await ds.driver.createSchemaBuilder().log();
  await ds.destroy();
  const quote = (query: string) => '`' + query.replace(/`/g, '\\`') + '`';
  const up = sql.upQueries.map((q) => `      await queryRunner.query(${quote(q.query)});`).join('\n');
  const down = sql.downQueries
    .reverse()
    .map((q) => `    await queryRunner.query(${quote(q.query)});`)
    .join('\n');
  process.stdout.write(`import { MigrationInterface, QueryRunner } from 'typeorm';

/**
 * Generated by src/scripts/generate-baseline-migration.ts from the entities
 * on an empty Postgres. An existing database (made by TYPEORM_SYNC before
 * migrations) already has this schema: the migration is then recorded
 * without running.
 */
export class ${name}${timestamp} implements MigrationInterface {
  name = '${name}${timestamp}';

  public async up(queryRunner: QueryRunner): Promise<void> {
    if (await queryRunner.hasTable('tasks')) return;
${up.replace(/^      /gm, '    ')}
  }

  public async down(queryRunner: QueryRunner): Promise<void> {
${down}
  }
}
`);
}

void main();
