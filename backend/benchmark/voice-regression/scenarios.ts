/**
 * Planner regression benchmark. Gold follows the spec where it is clear.
 * Conflicts are marked and are not auto-passed.
 * Production prompts are not edited here.
 */
import type { VoiceSessionTurn } from '../../src/modules/voice/voice-agent.types';
import type { BenchWorldId } from './world';

export type BenchCategory =
  | 'crud'
  | 'time'
  | 'context'
  | 'dependency'
  | 'reminder'
  | 'clarify'
  | 'tool'
  | 'plan';

export type ContractBasis = 'spec' | 'conflict';

export type FailureClass = 'hard' | 'semantic' | 'clarification' | 'tool';

export type Branch = {
  type: string;
  outcome?: 'answer' | 'clarify' | 'refuse';
  count?: number;
  must?: string[][];
  /** Each entry must match a different segment. */
  parts?: Array<{ must: string[][]; none?: string[] }>;
  answerMust?: string[][];
  answerNone?: string[];
  day?: string;
  editsMust?: string[][];
  question?: boolean;
};

export type BenchScenario = {
  id: string;
  category: BenchCategory;
  wave: 1 | 2;
  level: 'planner';
  utterance: string;
  history?: VoiceSessionTurn[];
  pendingClarification?: { segment: string; question: string } | null;
  pendingConfirmSummary?: string | null;
  plan?: 'today-interview';
  world?: BenchWorldId;
  contract: ContractBasis;
  contractNote: string;
  pipelineNote?: string;
  branches: Branch[];
  /** Every listed tool is required, unless toolMatch is any. */
  tools?: Array<{ name: string; day?: string }>;
  toolMatch?: 'all' | 'any';
  /** Stems in segment text that make a hard failure. Not applied to a spoken question. */
  hardIf: string[];
  /** Stems in the spoken reply, including a clarification, that make a hard failure. */
  spokenHardIf?: string[];
  semanticIf: string[];
  /** A segment that has a pronoun and not this stem is a hard wrong-target. */
  settledStem?: string;
  wrongType: FailureClass;
  countMismatch: FailureClass;
  emptyAnswer?: 'review';
  /** When set, one segment must carry every group. Count is not the gold. */
  finalState?: string[][];
  /** A parameter stem in the same segment as one of these antecedents was a guess. */
  ambiguousParam?: { param: string[]; antecedents: string[] };
  /**
   * The parameter was requested, but which antecedent it belongs to is not a unique gold.
   * Keeping the parameter is review, never pass. A missing parameter stays a semantic failure.
   */
  targetReview?: { param: string[]; reason: string };
  forbiddenDecisions?: Array<{ type: string; class: FailureClass }>;
  /** «звіт» copied from the open title, while «звітність» remains the spoken title. */
  copiedOpenTitle?: { forbidden: string; unless: string };
  forbid: string[];
};

const none: string[] = [];

function row(partial: BenchScenario): BenchScenario {
  return partial;
}

